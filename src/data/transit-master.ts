import type { AspectType } from '@/src/lib/astrology/constants'

// トランシット解説文
// キー: `${transitPlanet}-${natalPoint}-${category}`（例: "pluto-sun-conjunction"）
// category は合(conjunction)／ソフト(soft=三分・六分)／ハード(hard=矩・衝) の3区分
export type TransitAspectCategory = 'conjunction' | 'soft' | 'hard'

export function aspectCategory(aspect: AspectType): TransitAspectCategory {
  if (aspect === 'conjunction') return 'conjunction'
  if (aspect === 'trine' || aspect === 'sextile') return 'soft'
  return 'hard' // square, opposition, (semisquare, sesquiquadrate)
}

